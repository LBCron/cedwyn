"""Spill static snapshot builder 0.1.0 (Cedwyn webapp 44 of 59).

The browser reads only files generated by the migration build. The builder makes one
read-only snapshot of stats, guestbook and MCP tool metadata per Pages build.
Submissions, status checks, catalogue checks, agent execution and admin actions remain
on the existing cedwyn-spill API and Durable Object.
"""
API = "https://cedwyn.bucklerfamily.estate/spill/api"

def safe_json(fetch_json, url, fallback):
    try:
        value = fetch_json(url)
        return value if isinstance(value, dict) else fallback
    except Exception:
        return fallback

def build(ctx):
    fetch_json = ctx["fetch_json"]
    overview = safe_json(fetch_json, API + "/stats", {
        "available": False,
        "message": "A build-time statistics snapshot was unavailable. The live API remains available."
    })
    guestbook = safe_json(fetch_json, API + "/guestbook", {
        "available": False,
        "rows": [],
        "message": "A build-time guest-book snapshot was unavailable."
    })
    tools = safe_json(fetch_json, API + "/mcp", {
        "available": False,
        "tools": [],
        "message": "A build-time tool catalogue snapshot was unavailable."
    })
    overview["snapshot_source"] = API + "/stats"
    guestbook["snapshot_source"] = API + "/guestbook"
    tools["snapshot_source"] = API + "/mcp"
    return {
        "items": [],
        "views": {
            "overview": overview,
            "guestbook": guestbook,
            "tools": tools
        }
    }
